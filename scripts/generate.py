"""Regenerate src/wavvon/rest from a Wavvon-docs checkout.

    python scripts/generate.py [docs-path] [--ref <git-ref>]

docs-path defaults to ../../docs (the monorepo layout). With --ref the spec is
read from that commit instead of the working tree. The docs commit is written
to src/wavvon/rest/SPEC_COMMIT: `-dirty` means local edits, `+refnull` means
nullable_refs() patched the spec.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

from ruamel.yaml import YAML

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "wavvon" / "rest"


def nullable_refs(node: Any) -> bool:
    """OpenAPI 3.0 ignores siblings of `$ref`, so `{$ref, nullable: true}` is
    not nullable and the generated model raises on the hub's `null`. Wrap the
    ref in `anyOf`, which keeps `nullable`. Returns whether anything changed."""
    changed = False
    if isinstance(node, dict):
        if "$ref" in node and node.get("nullable"):
            node["anyOf"] = [{"$ref": node.pop("$ref")}]
            changed = True
        for v in node.values():
            changed |= nullable_refs(v)
    elif isinstance(node, list):
        for v in node:
            changed |= nullable_refs(v)
    return changed


def main() -> None:
    args = sys.argv[1:]
    ref = None
    if "--ref" in args:
        i = args.index("--ref")
        ref = args[i + 1]
        del args[i : i + 2]
    docs = (ROOT / (args[0] if args else "../../docs")).resolve()

    def git(*a: str) -> str:
        return subprocess.run(
            ["git", "-C", str(docs), *a], check=True, capture_output=True, text=True, encoding="utf-8"
        ).stdout.strip()

    commit = git("rev-parse", ref or "HEAD")
    text = git("show", f"{commit}:openapi.yaml") if ref else (docs / "openapi.yaml").read_text("utf-8")
    if not ref and git("status", "--porcelain", "--", "openapi.yaml"):
        commit += "-dirty"

    spec: dict[str, Any] = YAML(typ="safe").load(text)
    if nullable_refs(spec):
        print("WARNING: openapi.yaml marks a $ref nullable with a sibling, which OpenAPI 3.0 ignores; patched.")
        commit += "+refnull"

    with tempfile.TemporaryDirectory() as tmp:
        spec_path = Path(tmp) / "openapi.json"
        spec_path.write_text(json.dumps(spec), "utf-8")
        cfg = Path(tmp) / "config.json"
        cfg.write_text(json.dumps({"use_path_prefixes_for_title_model_names": False}))
        out = Path(tmp) / "out"
        bindir = Path(sys.executable).parent
        env = {**os.environ, "PATH": f"{bindir}{os.pathsep}{os.environ.get('PATH', '')}"}
        subprocess.run(
            [
                str(bindir / "openapi-python-client"),
                "generate",
                "--path",
                str(spec_path),
                "--config",
                str(cfg),
                "--meta",
                "none",
                "--output-path",
                str(out),
                "--overwrite",
            ],
            check=True,
            env=env,
        )
        shutil.rmtree(OUT, ignore_errors=True)
        shutil.copytree(out, OUT)

    for f in OUT.rglob("*.py"):
        f.write_bytes(f.read_bytes().replace(b"\r\n", b"\n"))
    init = OUT / "__init__.py"
    header = f'"""Generated by scripts/generate.py from Wavvon-docs openapi.yaml @ {commit}. Do not edit."""\n'
    init.write_bytes((header + re.sub(r'^""".*?"""\n', "", init.read_text("utf-8"), flags=re.S)).encode())
    (OUT / "SPEC_COMMIT").write_bytes(f"{commit}\n".encode())
    print(f"src/wavvon/rest generated from Wavvon-docs {commit}")


if __name__ == "__main__":
    main()
