"""Regenerate src/wavvon/rest from a Wavvon-docs checkout.

    python scripts/generate.py [docs-path] [--ref <git-ref>]

docs-path defaults to ../../docs (the monorepo layout). With --ref the spec is
read from that commit instead of the working tree. The docs commit is written
to src/wavvon/rest/SPEC_COMMIT: `-dirty` means local edits, `+lax` means
responses were patched to satisfy openapi-python-client (see lax()).
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

from ruamel.yaml import YAML

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "wavvon" / "rest"

METHODS = {"get", "put", "post", "delete", "patch", "head", "options"}


def lax(spec: dict[str, Any]) -> bool:
    """OpenAPI requires `responses` on every operation and `description` on
    every response; openapi-python-client enforces both and openapi.yaml omits
    them in places. Fill in empty ones. Returns whether anything changed."""
    changed = False
    for item in spec.get("paths", {}).values():
        for method, op in item.items():
            if method not in METHODS:
                continue
            if "responses" not in op:
                op["responses"] = {"default": {"description": ""}}
                changed = True
            for resp in op["responses"].values():
                if "$ref" not in resp and "description" not in resp:
                    resp["description"] = ""
                    changed = True
    return changed


def py310(code: str) -> str:
    """The generator emits typing.Self and enum.StrEnum, both 3.11+. Rewrite
    them so the package still imports on 3.10. Every generated enum overrides
    __str__ to return its value, so (str, Enum) behaves the same."""

    def fix(m: re.Match[str]) -> str:
        names = [n.strip() for n in m.group(1).split(",")]
        if "Self" not in names:
            return m.group(0)
        rest = [n for n in names if n != "Self"]
        return (f"from typing import {', '.join(rest)}\n" if rest else "") + "from typing_extensions import Self"

    code = re.sub(r"^from typing import ([^(\n]*)$", fix, code, flags=re.M)
    return code.replace("from enum import StrEnum", "from enum import Enum").replace("(StrEnum):", "(str, Enum):")


def main() -> None:
    args = sys.argv[1:]
    ref = None
    if "--ref" in args:
        i = args.index("--ref")
        ref = args[i + 1]
        del args[i : i + 2]
    docs = (ROOT / (args[0] if args else "../../docs")).resolve()

    def git(*a: str) -> str:
        return subprocess.run(
            ["git", "-C", str(docs), *a], check=True, capture_output=True, text=True, encoding="utf-8"
        ).stdout.strip()

    commit = git("rev-parse", ref or "HEAD")
    text = git("show", f"{commit}:openapi.yaml") if ref else (docs / "openapi.yaml").read_text("utf-8")
    if not ref and git("status", "--porcelain", "--", "openapi.yaml"):
        commit += "-dirty"

    spec: dict[str, Any] = YAML(typ="safe").load(text)
    if lax(spec):
        print("WARNING: openapi.yaml has operations or responses without the required description; patched.")
        commit += "+lax"

    with tempfile.TemporaryDirectory() as tmp:
        spec_path = Path(tmp) / "openapi.json"
        spec_path.write_text(json.dumps(spec), "utf-8")
        cfg = Path(tmp) / "config.json"
        cfg.write_text(json.dumps({"use_path_prefixes_for_title_model_names": False}))
        out = Path(tmp) / "out"
        bindir = Path(sys.executable).parent
        env = {**os.environ, "PATH": f"{bindir}{os.pathsep}{os.environ.get('PATH', '')}"}
        subprocess.run(
            [
                str(bindir / "openapi-python-client"),
                "generate",
                "--path",
                str(spec_path),
                "--config",
                str(cfg),
                "--meta",
                "none",
                "--output-path",
                str(out),
                "--overwrite",
            ],
            check=True,
            env=env,
        )
        shutil.rmtree(OUT, ignore_errors=True)
        shutil.copytree(out, OUT)

    for f in OUT.rglob("*.py"):
        f.write_bytes(py310(f.read_bytes().decode("utf-8").replace("\r\n", "\n")).encode())
    init = OUT / "__init__.py"
    header = f'"""Generated by scripts/generate.py from Wavvon-docs openapi.yaml @ {commit}. Do not edit."""\n'
    init.write_bytes((header + re.sub(r'^""".*?"""\n', "", init.read_text("utf-8"), flags=re.S)).encode())
    (OUT / "SPEC_COMMIT").write_bytes(f"{commit}\n".encode())
    print(f"src/wavvon/rest generated from Wavvon-docs {commit}")


if __name__ == "__main__":
    main()
